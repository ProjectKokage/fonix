    def _write_apk(
        self,
        *,
        include_cxx: bool = True,
        include_jni: bool = False,
        extra_libraries: tuple[tuple[str, bytes], ...] = (),
    ) -> None:
        with zipfile.ZipFile(self.final_apk, "w") as archive:
            archive.writestr("AndroidManifest.xml", b"synthetic manifest")
            archive.writestr(f"lib/{self.abi}/libonnxruntime.so", self.ort_bytes)
            archive.writestr(f"lib/{self.abi}/libfonix_shim.so", self.shim_bytes)
            archive.writestr(
                f"lib/{self.abi}/libsherpa-onnx-c-api.so", self.sherpa_capi_bytes
            )
            if include_cxx:
                archive.writestr(
                    f"lib/{self.abi}/libsherpa-onnx-cxx-api.so",
                    self.sherpa_cxx_bytes,
                )
            if include_jni:
                archive.writestr(
                    f"lib/{self.abi}/libsherpa-onnx-jni.so",
                    ELF_FIXTURE.synthetic_elf(
                        self.abi,
                        soname="libsherpa-onnx-jni.so",
                        needed=("libonnxruntime.so", "libc.so"),
                    ),
                )
            for name, contents in extra_libraries:
                archive.writestr(f"lib/{self.abi}/{name}", contents)

