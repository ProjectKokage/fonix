    def test_atomic_publication_never_overwrites_a_racing_destination(self) -> None:
        output = self.root / "racing-output.json"
        real_link = VALIDATOR.os.link

        def create_destination_before_link(
            source: Path, destination: Path, *, follow_symlinks: bool
        ) -> None:
            Path(destination).write_bytes(b"racing owner\n")
            real_link(source, destination, follow_symlinks=follow_symlinks)

        with mock.patch.object(VALIDATOR.os, "link", side_effect=create_destination_before_link):
            with self.assertRaises(FileExistsError):
                VALIDATOR._write_new(output, {"result": "passed"})
        self.assertEqual(output.read_bytes(), b"racing owner\n")
        self.assertFalse((self.root / "racing-output.json.tmp").exists())

        second_output = self.root / "racing-temporary-output.json"
        temporary = self.root / "racing-temporary-output.json.tmp"
        real_open = VALIDATOR.os.open

        def create_temporary_before_open(
            path: Path, flags: int, mode: int = 0o777
        ) -> int:
            Path(path).write_bytes(b"temporary owner\n")
            return real_open(path, flags, mode)

        with mock.patch.object(VALIDATOR.os, "open", side_effect=create_temporary_before_open):
            with self.assertRaises(FileExistsError):
                VALIDATOR._write_new(second_output, {"result": "passed"})
        self.assertEqual(temporary.read_bytes(), b"temporary owner\n")
        self.assertFalse(second_output.exists())

        mutated_output = self.root / "mutated-publication.json"

        def mutate_owned_inode_after_link(
            source: Path, destination: Path, *, follow_symlinks: bool
        ) -> None:
            real_link(source, destination, follow_symlinks=follow_symlinks)
            published = Path(destination)
            published.write_bytes(
                published.read_bytes().replace(b'"passed"', b'"failed"')
            )

        with mock.patch.object(
            VALIDATOR.os, "link", side_effect=mutate_owned_inode_after_link
        ):
            with self.assertRaisesRegex(
                VALIDATOR.LoadOrderReceiptError,
                "published output changed during publication",
            ):
                VALIDATOR._write_new(mutated_output, {"result": "passed"})
        self.assertFalse(mutated_output.exists())
        self.assertFalse((self.root / "mutated-publication.json.tmp").exists())

        failed_output = self.root / "failed-publication.json"

        def fail_after_link(
            source: Path, destination: Path, *, follow_symlinks: bool
        ) -> None:
            real_link(source, destination, follow_symlinks=follow_symlinks)
            raise OSError("synthetic post-link failure")

        with mock.patch.object(VALIDATOR.os, "link", side_effect=fail_after_link):
            with self.assertRaisesRegex(OSError, "synthetic post-link failure"):
                VALIDATOR._write_new(failed_output, {"result": "passed"})
        self.assertFalse(failed_output.exists())
        self.assertFalse((self.root / "failed-publication.json.tmp").exists())

