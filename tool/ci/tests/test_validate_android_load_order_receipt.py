    def test_schema_is_v2_and_closed(self) -> None:
        schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
        self.assertEqual(schema["properties"]["schemaVersion"]["const"], 2)
        self.assertFalse(schema["additionalProperties"])
        self.assertFalse(schema["$defs"]["lifecycle"]["additionalProperties"])
        VALIDATOR._validate_schema_document(schema)

        duplicated = copy.deepcopy(schema)
        duplicated["$defs"]["sherpaProfile"]["required"].append("id")
        with self.assertRaisesRegex(
            VALIDATOR.LoadOrderReceiptError, "unique string property names"
        ):
            VALIDATOR._validate_schema_document(duplicated)

