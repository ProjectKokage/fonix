    def _run(
        self, name: str | Path = "validated.json"
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), *self._arguments(self.root / name)],
            cwd=REPOSITORY,
            check=False,
            capture_output=True,
            text=True,
        )

    def _assert_rejected(self, expected: str) -> None:
        result = self._run()
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn(expected, result.stderr)
        self.assertFalse((self.root / "validated.json").exists())

    def test_accepts_complete_evidence_and_output_is_path_free_deterministic(self) -> None:
        first = self._run("first.json")
        self.assertEqual(first.returncode, 0, first.stderr)
        second = self._run("second.json")
        self.assertEqual(second.returncode, 0, second.stderr)
        first_bytes = (self.root / "first.json").read_bytes()
        self.assertEqual(first_bytes, (self.root / "second.json").read_bytes())
        record = json.loads(first_bytes)
        self.assertEqual(record["schemaVersion"], 1)
        self.assertEqual(record["result"], "passed")
        self.assertEqual(
            set(record),
            {
                "schemaVersion",
                "result",
                "claimStatus",
                "targetEvidenceProvenance",
                "validatorSha256",
                "receiptSchemaSha256",
                "nativeVerifierSha256",
                "loadOrderReceiptSha256",
                "matrix",
                "build",
                "device",
                "process",
                "runtime",
                "sherpa",
                "fixtures",
                "initialization",
                "workload",
                "lifecycle",
                "evidenceBindings",
                "nativeLibraries",
                "claimBoundary",
            },
        )
        self.assertNotIn(str(self.root), first_bytes.decode("utf-8"))
        self.assertEqual(record["claimStatus"], "offline-consistency-only")
        self.assertEqual(record["targetEvidenceProvenance"], "unverified")
        self.assertIn("between bounded VAD frames", record["claimBoundary"])
        self.assertIn("does not authenticate", record["claimBoundary"])
        self.assertIn("trusted capture provenance remains required", record["claimBoundary"])
        self.assertEqual(record["validatorSha256"], _sha256(SCRIPT))
        self.assertEqual(record["receiptSchemaSha256"], _sha256(SCHEMA))
        self.assertEqual(record["nativeVerifierSha256"], _sha256(VALIDATOR.VERIFIER_PATH))
        self.assertEqual(
            record["evidenceBindings"]["receiptSchema"],
            {"sizeBytes": SCHEMA.stat().st_size, "sha256": _sha256(SCHEMA)},
        )
        self.assertEqual(
            record["evidenceBindings"]["nativeVerifier"],
            {
                "sizeBytes": VALIDATOR.VERIFIER_PATH.stat().st_size,
                "sha256": _sha256(VALIDATOR.VERIFIER_PATH),
            },
        )
        self.assertEqual(
            record["nativeLibraries"]["onnxRuntime"]["sha256"],
            self.receipt["runtime"]["ortSha256"],
        )

